def draw(screen):
    for y in range(board_y):
        for x in range(board_x):
            X = x * (length + gap) + gap
            Y = y * (length + gap) + gap

            if board[y][x] == 0:
                pygame.draw.rect(screen, BG, [X, Y, length, length], border_radius = 2)
            if board[y][x] == 1:
                pygame.draw.rect(screen, WLL, [X, Y, length, length], border_radius = 2)


def main():
    global board, board_y, board_x, tab_y, tab_x
    pygame.init()
    pygame.display.set_caption("Pac-Man 002")
    screen = pygame.display.set_mode((tab_x, tab_y))
    clock = pygame.time.Clock()

    font = pygame.font.Font(None, 50)

    while True:
        for event in pygame.event.get():
            if event.type == pygame.QUIT:
                pygame.quit()
                sys.exit()
        screen.fill(BG)
        draw(screen)

        pygame.display.flip()
        clock.tick(60)

if __name__ == '__main__':
    main()
