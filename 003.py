# Bololean Values
def check(direction):
    if direction == 3:
        return (plyr[1] + 1 <= board_x - 1 and board[plyr[0]][plyr[1] + 1] != 1)
    elif direction == 6:
        return (plyr[0] + 1 <= board_y - 1 and board[plyr[0] + 1][plyr[1]] != 1)
    elif direction == 9:
        return (plyr[1] - 1 >= 0 and board[plyr[0]][plyr[1] - 1] != 1)
    elif direction == 12:
        return (plyr[0] - 1 >= 0 and board[plyr[0] - 1][plyr[1]] != 1)

def spawn():
    global plyr, drct
    plyr = [15, 13]
    drct = 0

lock = threading.Lock()
def move():
    global plyr, drct
    while True:
        time.sleep(0.5)
        with lock:
            plyr_to_brd(0)
            if (drct == 3 and plyr == [12, 27]): plyr = [12, -1]
            if (drct == 9 and plyr == [12, 0]): plyr = [12, 27]

            elif check(drct):
                if drct == 3:
                    plyr[1] += 1
                elif drct == 6:
                    plyr[0] += 1
                elif drct == 9:
                    plyr[1] -= 1
                elif drct == 12:
                    plyr[0] -= 1
            plyr_to_brd(2)

def plyr_to_brd(state):
    board[plyr[0]][plyr[1]] = state

def draw(screen):
    for y in range(board_y):
        for x in range(board_x):
            X = x * (length + gap) + gap
            Y = y * (length + gap) + gap

            if board[y][x] == 0:
                pygame.draw.rect(screen, BG, [X, Y, length, length], border_radius = 2)
            if board[y][x] == 1:
                pygame.draw.rect(screen, WLL, [X, Y, length, length], border_radius = 2)
            if board[y][x] == 2:
                pygame.draw.rect(screen, ACTV, [X, Y, length, length], border_radius = 2)


def main():
    global board, board_y, board_x, tab_y, tab_x, plyr, drct
    pygame.init()
    pygame.display.set_caption("Pac-Man 003")
    screen = pygame.display.set_mode((tab_x, tab_y))
    clock = pygame.time.Clock()

    font = pygame.font.Font(None, 50)

    spawn()

    bg_thread = threading.Thread(target=move, daemon=True)
    bg_thread.start()

    while True:
        for event in pygame.event.get():
            if event.type == pygame.QUIT:
                pygame.quit()
                sys.exit()
            if event.type == pygame.KEYDOWN:
                if event.key == pygame.K_RIGHT:
                    drct = 3
                if event.key == pygame.K_DOWN:
                    drct = 6
                if event.key == pygame.K_LEFT:
                    drct = 9
                if event.key == pygame.K_UP:
                    drct = 12

        screen.fill(BG)

        with lock:
            draw(screen)

        pygame.display.flip()
        clock.tick(60)

if __name__ == '__main__':
    main()